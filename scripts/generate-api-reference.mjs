/**
 * Writes site/src/data/api-reference.md from the public API in src/index.ts.
 *
 * `site/typedoc.json` still emits the docs MDX stub. This script uses a
 * separate TypeDoc run so members stay on one page: the site renders that
 * markdown directly because compiling the full MDX tree exhausts the dev server.
 */
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const output = path.join(root, 'site/src/data/api-reference.md');
const work = mkdtempSync(path.join(tmpdir(), 'g6lite-api-'));
const outDir = path.join(work, 'out');
const configPath = path.join(work, 'typedoc.json');

const config = {
  $schema: 'https://typedoc.org/schema.json',
  entryPoints: [path.join(root, 'src/index.ts')],
  tsconfig: path.join(root, 'tsconfig.json'),
  out: outDir,
  cleanOutputDir: true,
  plugin: ['typedoc-plugin-markdown'],
  readme: 'none',
  githubPages: false,
  hideGenerator: true,
  excludeInternal: true,
  excludePrivate: true,
  sort: ['source-order'],
  router: 'member',
  membersWithOwnFile: [],
  entryFileName: 'index',
  fileExtension: '.md',
  useCodeBlocks: true,
  expandObjects: true,
  expandParameters: true,
  parametersFormat: 'table',
  indexFormat: 'table',
  hidePageHeader: true,
  hideBreadcrumbs: true,
  useHTMLAnchors: false,
};

writeFileSync(configPath, JSON.stringify(config, null, 2));

const typedoc = spawnSync('npx', ['typedoc', '--options', configPath], {
  cwd: root,
  stdio: 'inherit',
});
if (typedoc.status !== 0) {
  rmSync(work, { recursive: true, force: true });
  process.exit(typedoc.status ?? 1);
}

function markdownFiles(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...markdownFiles(full));
    else if (entry.name.endsWith('.md')) files.push(full);
  }
  return files;
}

const files = markdownFiles(outDir);
if (files.length === 0) {
  console.error('generate-api-reference: TypeDoc wrote no markdown');
  rmSync(work, { recursive: true, force: true });
  process.exit(1);
}

files.sort((left, right) => statSync(right).size - statSync(left).size);
const source = files[0];
let markdown = readFileSync(source, 'utf8').replace(/^---\n[\s\S]*?\n---\n+/, '');
const banner =
  '<!-- Generated by scripts/generate-api-reference.mjs from src/index.ts. Do not edit by hand. -->\n\n';
if (!markdown.startsWith('<!-- Generated by scripts/generate-api-reference.mjs')) {
  markdown = banner + markdown;
}
if (!markdown.endsWith('\n')) markdown += '\n';
writeFileSync(output, markdown);
rmSync(work, { recursive: true, force: true });
console.log(
  `generate-api-reference: wrote ${path.relative(root, output)} from ${path.basename(source)} (${files.length} markdown file${files.length === 1 ? '' : 's'})`,
);
