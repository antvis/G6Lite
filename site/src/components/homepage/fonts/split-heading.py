"""Split the licensed heading font; print the Next.js config to stdout.

Run with fonttools[woff]==4.61.1. The source WOFF2 is kept for reproducibility.
Only binary font assets are written. Apply the printed config to site-font.ts.
"""

from pathlib import Path
import sys

from fontTools import subset
from fontTools.ttLib import TTFont


def unicode_range(codepoints):
    """Compact a sorted set of codepoints into CSS unicode-range syntax."""
    ranges = []
    start = end = None
    for codepoint in sorted(codepoints):
        if start is None:
            start = end = codepoint
        elif codepoint == end + 1:
            end = codepoint
        else:
            ranges.append((start, end))
            start = end = codepoint
    if start is not None:
        ranges.append((start, end))
    return ','.join(
        f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}'
        for start, end in ranges
    )


directory = Path(__file__).resolve().parent
source = directory / 'heading-medium.woff2'
coverage = set(TTFont(source).getBestCmap())
latin = {codepoint for codepoint in coverage if codepoint < 0x3000}
common = {
    ord(char) for char in (directory / 'common-headings.txt').read_text(encoding='utf-8')
} & (coverage - latin)
groups = {
    'latin': latin,
    'common': common,
    'remaining': coverage - latin - common,
}

print("import localFont from 'next/font/local';\n")
print('// Generated by components/homepage/fonts/split-heading.py.')
print('// Disjoint unicode ranges preserve coverage without downloading unused glyphs.')
for name, codepoints in groups.items():
    font = TTFont(source, recalcTimestamp=False)
    options = subset.Options()
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17]
    options.name_languages = [0x409]
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    font.flavor = 'woff2'
    output = directory / f'heading-{name}.woff2'
    font.save(output)
    print(f'const heading{name.title()} = localFont({{')
    print(f"  src: '../components/homepage/fonts/{output.name}',")
    print("  weight: '500',")
    print("  display: 'swap',")
    print('  preload: false,')
    print(f"  variable: '--font-heading-{name}',")
    print('  adjustFontFallback: false,')
    print(f"  declarations: [{{ prop: 'unicode-range', value: '{unicode_range(codepoints)}' }}],")
    print('});\n')
    print(f'{output.name}: {output.stat().st_size} bytes; {len(codepoints)} codepoints', file=sys.stderr)

print('export const headingFont = {')
print("  variable: [headingLatin.variable, headingCommon.variable, headingRemaining.variable].join(' '),")
print('};')
